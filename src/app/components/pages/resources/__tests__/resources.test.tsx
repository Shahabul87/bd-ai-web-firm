describe('Resources messages', () => {
  type Q = { chip: string; text: string; terms: string[] };
  const en = (enMessages as unknown as { Resources: { retrieval: { queries: Q[] } } }).Resources;
  const bn = (bnMessages as unknown as { Resources: { retrieval: { queries: Q[] } } }).Resources;

  it('uses the same key terms in both locales (the content is English)', () => {
    expect(bn.retrieval.queries.map((q) => q.terms)).toEqual(en.retrieval.queries.map((q) => q.terms));
    expect(en.retrieval.queries.length).toBeGreaterThanOrEqual(3);
  });
});

describe('ArticleShell', () => {
  const path = join(process.cwd(), '.velite', 'blogs.json');
  const run = existsSync(path) ? it : it.skip;

  run('renders a real post: one h1, a TOC that links to every section, the MDX body', () => {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const ArticleShell = require('../ArticleShell').default as typeof import('../ArticleShell').default;
    const [doc] = JSON.parse(readFileSync(path, 'utf8')) as { title: string; excerpt: string; content: string }[];
    const { container } = render(
      <ArticleShell
        id="t"
        kicker="Blog"
        back={{ href: '/resources/blog', label: 'All posts' }}
        title={doc.title}
        dek={doc.excerpt}
        meta={[{ label: '1 January 2026', dateTime: '2026-01-01' }]}
        tags={['AI']}
        code={doc.content}
        labels={{ toc: 'On this page', tags: 'Tags' }}
      />,
    );
    expect(screen.getAllByRole('heading', { level: 1 })).toHaveLength(1);
    const toc = screen.getByRole('navigation', { name: 'On this page' });
    const targets = within(toc)
      .getAllByRole('link')
      .map((a) => a.getAttribute('href')?.slice(1));
    expect(targets.length).toBeGreaterThan(0);
    for (const id of targets) expect(container.querySelector(`.rs-prose [id="${id}"]`)).not.toBeNull();
  });
});
