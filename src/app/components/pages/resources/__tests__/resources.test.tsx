const item = (key: string, title: string, excerpt = '', tags: string[] = []): LibraryItem => ({
  key,
  type: 'blog',
  slug: key,
  href: `/resources/blog/${key}`,
  title,
  excerpt,
  tags,
  date: '2026-01-01',
});

const LIB = [
  item('a', 'Choosing a web app', 'A framework for the decision', ['web']),
  item('b', 'Measuring AI quality', 'Evals that tell you whether it is getting better', ['ai']),
  item('c', 'Unrelated', 'Nothing here', []),
];

describe('retrieval scoring', () => {
  it('stems lightly', () => {
    expect(stem('measured')).toBe('measur');
    expect(stem('measuring')).toBe('measur');
    expect(stem('apps')).toBe('app');
    expect(stem('ai')).toBe('ai');
  });

  it('scores 2 per title term, 1 per description/tag term, normalised', () => {
    expect(score(['ai', 'quality'], LIB[1])).toBe(1);
    expect(score(['better'], LIB[1])).toBe(0.5);
    expect(score(['web', 'nothing'], LIB[0])).toBe(0.5);
    expect(score([], LIB[0])).toBe(0);
  });

  it('ranks best first with stable ties and is deterministic', () => {
    const r = rank(['ai', 'measure'], LIB);
    expect(r.map((x) => x.key)).toEqual(['b', 'a', 'c']);
    expect(rank(['ai', 'measure'], LIB)).toEqual(r);
  });

  it('finds related items, never itself, and drops zero overlap', () => {
    const r = related(LIB[1], LIB);
    expect(r.every((x) => x.key !== 'b' && x.score > 0)).toBe(true);
  });

  it('marks matching title words', () => {
    const words = splitWords('Measuring AI quality');
    expect(titleHits(['ai'], 'Measuring AI quality').map((i) => words[i])).toEqual(['AI']);
  });
});

describe('table of contents extraction', () => {
  it('pulls the h2 headings out of the compiled content', () => {
    for (const file of ['blogs', 'guides']) {
      // .velite is generated by the dev/build pipeline; nothing to check before it exists.
      const path = join(process.cwd(), '.velite', `${file}.json`);
      if (!existsSync(path)) continue;
      const docs = JSON.parse(readFileSync(path, 'utf8')) as { content: string }[];
      for (const doc of docs) {
        const hs = extractHeadings(doc.content);
        expect(hs.length).toBeGreaterThan(0);
        for (const h of hs) {
          expect(doc.content).toContain(`id:"${h.id}"`);
          expect(h.text.length).toBeGreaterThan(0);
        }
      }
    }
  });
});

const LABELS: DemoLabels = {
  label: 'Retrieval',
  example: 'Over this library',
  chipsLabel: 'Example questions',
  queryLabel: 'Question',
  termsLabel: 'Key terms',
  resultsLabel: 'Results',
  ranking: 'Ranking',
  pause: 'Pause',
  play: 'Play',
  note: 'Word overlap',
  topMatch: 'Top match',
};

describe('RetrievalDemo', () => {
  const queries = [
    { chip: 'Quality', text: 'How do we know the AI is getting better?', terms: ['ai', 'better'] },
    { chip: 'Web', text: 'Web or mobile?', terms: ['web'] },
  ];
  const rankings: DemoRanking[] = queries.map((q) => {
    const r = rank(q.terms, LIB);
    return {
      order: r.map((x) => x.key),
      scores: Object.fromEntries(r.map((x) => [x.key, { value: x.score, label: x.score.toFixed(2) }])),
      hits: Object.fromEntries(LIB.map((it) => [it.key, titleHits(q.terms, it.title)])),
    };
  });

  it('server-renders the finished ranking of the first question as links', () => {
    render(
      <RetrievalDemo
        queries={queries}
        items={LIB.map((it) => ({ key: it.key, href: it.href, title: it.title, typeLabel: 'Blog' }))}
        rankings={rankings}
        labels={LABELS}
      />,
    );
    const links = within(screen.getByRole('list')).getAllByRole('link');
    expect(links.map((a) => a.getAttribute('href'))).toEqual(rankings[0].order.map((k) => `/resources/blog/${k}`));
    expect(screen.getByRole('button', { name: 'Quality' })).toHaveAttribute('aria-pressed', 'true');
  });

  it('pins a question from its chip', () => {
    render(
      <RetrievalDemo
        queries={queries}
        items={LIB.map((it) => ({ key: it.key, href: it.href, title: it.title, typeLabel: 'Blog' }))}
        rankings={rankings}
        labels={LABELS}
      />,
    );
    fireEvent.click(screen.getByRole('button', { name: 'Web' }));
    expect(screen.getByRole('button', { name: 'Web' })).toHaveAttribute('aria-pressed', 'true');
    expect(screen.getByRole('status')).toHaveTextContent('Top match: Choosing a web app');
  });
});

